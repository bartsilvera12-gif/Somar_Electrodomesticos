-- =====================================================================
--  TRIGGERS updated_at
-- =====================================================================
do $$
declare t text;
begin
  foreach t in array array[
    'admin_users','site_settings','categories','brands','products',
    'product_installments','benefits','purchase_steps','testimonials','banners'
  ]
  loop
    execute format(
      'drop trigger if exists trg_set_updated_at on somarelectrodomesticos.%1$I;
       create trigger trg_set_updated_at before update on somarelectrodomesticos.%1$I
       for each row execute function somarelectrodomesticos.set_updated_at();', t);
  end loop;
end$$;

-- =====================================================================

create schema if not exists somarelectrodomesticos;

-- Extensiones útiles (por si no están)
create extension if not exists pgcrypto;

-- is_admin() referencia admin_users, que se crea más abajo. Con esto Postgres
-- NO valida el cuerpo de las funciones al crearlas (se valida en runtime, cuando
-- la tabla ya existe). Evita el error 42P01 al ejecutar toda la migración de una.
set check_function_bodies = off;

-- ---------------------------------------------------------------------
--  Función reutilizable: updated_at automático
-- ---------------------------------------------------------------------
create or replace function somarelectrodomesticos.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------
--  Función de seguridad: ¿el usuario actual es admin activo?
--  SECURITY DEFINER para poder leer admin_users saltando su RLS.
-- ---------------------------------------------------------------------
create or replace function somarelectrodomesticos.is_admin()
returns boolean
language sql
stable
security definer
set search_path = somarelectrodomesticos, public
as $$
  select exists (
    select 1
    from somarelectrodomesticos.admin_users au
    where au.user_id = auth.uid()
      and au.is_active = true
  );
$$;

